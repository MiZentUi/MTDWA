def env_bool(name: str, default: bool) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.lower() in {"1", "true", "yes", "on"}


def detect_time_zone() -> str:
    try:
        from tzlocal import get_localzone_name
    except ImportError:
        return "UTC"

    try:
        return get_localzone_name()
    except Exception:
        return "UTC"


